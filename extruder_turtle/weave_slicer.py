# takes a turtle + a shape as input and slices with WeaveSlicer, using wall width and wavelength
# input: turtle (.gcode file associted with turtle), shape to slice, and slicing parameters 
# output: list of layers
def weave_slice_turtle (t,shape,wall_width=3.0,wavelength=3.0, mode=1, bottom_layers=0, skin=False,pattern=False,pattern_padding=0):
	t.write_gcode_comment("**************************************************")
	t.write_gcode_comment("******* file generated by WeaveSlicer ************")
	t.write_gcode_comment("******* conception: Camila Friedman-Gerlicz ******")
	t.write_gcode_comment("****** python implementation: Leah Buechley ******")
	t.write_gcode_comment("************** 2023 - present ********************")
	t.write_gcode_comment("**************************************************")
	layer_height = t.get_layer_height()
	shape_slices = su.slice_shape(shape,layer_height=layer_height)
	layers = []

	# for all slices in shape
	for i in range(0,len(shape_slices)):
		if (pattern is not False and i>bottom_layers+pattern_padding and i<len(shape_slices)-pattern_padding):
			# find correct vertical index into pattern
			ratio = len(pattern)/len(shape_slices)
			pattern_index = int(round(i*ratio,0))
			pattern_row = pattern[pattern_index]
		else:
			pattern_row=False
		x,points = weave_one_slice_turtle(t=t,layer=i,shape=shape,wall_width=wall_width,wavelength=wavelength, mode=mode, bottom_layers=bottom_layers, skin=skin, shape_slices=shape_slices,pattern_row=pattern_row)
		layers.append(x)

	return layers,points

def weave_information_turtle (t,shape,wall_width=3.0,wavelength=3.0, mode=1, bottom_layers=0, skin=False,pattern=False,pattern_padding=0):
	layer_height = t.get_layer_height()
	shape_slices = su.slice_shape(shape,layer_height=layer_height)
	layers = len(shape_slices)

	# for all slices in shape
	max_oscillations=0
	min_oscillations=1000
	for i in range(0,len(shape_slices)-1):
		slice0 = shape_slices[i][0] # current slice
		slice1 = shape_slices[i+1][0]
		points,points1,angles = find_points_and_angles(slice0, slice1, wavelength, mode=mode, wall_width=wall_width, layer=i)
		oscillations = len(points)
		if (oscillations>max_oscillations):
			max_oscillations = oscillations
		if (oscillations<min_oscillations):
			min_oscillations = oscillations

	return round(min_oscillations/4,0), round(max_oscillations/4,0), layers


# takes a turtle, shape, and layer number as input and slices that layer with WeaveSlicer, using wall width and wavelength
# input: turtle (.gcode file associted with turtle), layer number, shape to slice, and slicing parameters 
# output: sliced layer
def weave_one_slice_turtle (t,layer,shape,wall_width=3.0,wavelength=3.0, mode=1, bottom_layers=0, skin=False, shape_slices=False,pattern_row=False,randomize=False):
	# print("layer: " +str(layer))
	layer_height = t.get_layer_height()
	original_speed = t.get_speed()
	original_extrude = t.get_extrude_rate()
	if (shape_slices==False):
		shape_slices = su.slice_shape(shape,layer_height=layer_height)
	if (layer%2==0):
		offset=True
	else:
		offset=False
	k=0
	i = layer
	layers = []
	skin_offset_factor = .6

	# if top layer:
	if (layer==len(shape_slices)-1): 
		slice0 = shape_slices[i-1][k] # previous slice
		slice1 = shape_slices[i][k] # current slice
		if (skin==True):
			point = rs.CurveAreaCentroid(slice0)[0]
			slice0 = rs.OffsetCurve(slice0,point,t.get_extrude_width()*skin_offset_factor)[0]
			point = rs.CurveAreaCentroid(slice1)[0]
			slice1 = rs.OffsetCurve(slice1,point,t.get_extrude_width()*skin_offset_factor)[0]
		points,points1,angles = find_points_and_angles(slice0,slice1,wavelength,wall_width=wall_width,mode=mode,layer=i)
		if (points and points1 and angles):
			interior_points, exterior_points, x=weave_points_and_angles(t,points1,points1,angles,slice1,slice1,wall_width=wall_width,mode=mode,offset=offset, top=True,skin=skin)
			if (skin==True):
				generate_skin(t,points=exterior_points, skin_offset_factor=skin_offset_factor,offset=offset)
		else:
			x = -1

		return x,points1

	# all other layers
	while (k<len(shape_slices[i])):
	# for all branches in current slice
		slice0 = shape_slices[i][k] # current slice
		original_slice = slice0

		if (len(shape_slices[i])==1):
			# if there is just one branch, use slice above to compute angles
			slice1 = shape_slices[i+1][k] # slice above
		else:
			# if there is more than one branch, lift pen and find the slice above
			t.penup()
			# if a branch is closing there may not be a matching branch above
			if (len(shape_slices[i+1])>k):
			# if there is a matching branch above:
				# try easy guess first
				slice1 = shape_slices[i+1][k] # slice above
			else:
			# if there is no matching branch above
				# find closest slice because you have to
				index = su.find_closest_slice(slice0,shape_slices[i+1]) 
				slice1 = shape_slices[i+1][index] # next slice
		
		if (skin==True):
			point = rs.CurveAreaCentroid(slice0)[0]
			slice0 = rs.OffsetCurve(slice0,point,t.get_extrude_width()*skin_offset_factor)[0]
			point = rs.CurveAreaCentroid(slice1)[0]
			slice1 = rs.OffsetCurve(slice1,point,t.get_extrude_width()*skin_offset_factor)[0]

		points,points1,angles = find_points_and_angles(slice0,slice1,wavelength,wall_width=wall_width,mode=mode,layer=i)
		count=0
		while (angles is not False and angles[0]>85 and angles[0]<95 and count<5):
			# if the angle is close to 90
			# a co-planar slice was found
			# this is probably the wrong one, try to find a better one
			index = su.find_closest_slice(slice0,shape_slices[i+1]) 
			slice1 = shape_slices[i+1][index] # next slice
			points,points1,angles = find_points_and_angles(slice0,slice1,wavelength,wall_width=wall_width,mode=mode,layer=i)
			count+=1
		if (points is not False and angles is not False):
			if (pattern_row is False):
				interior_points, exterior_points, x=weave_points_and_angles(t,points,points1,angles,slice0,slice1,wall_width=wall_width,mode=mode,offset=offset,skin=skin,randomize=randomize)
			else:
				if (layer%2==0):
					reverse=True
				else:
					reverse=False
				interior_points, exterior_points, x=weave_points_and_angles_pattern(t,pattern_row,points,points1,angles,slice0,slice1,wall_width=wall_width,mode=mode,offset=offset,skin=skin,reverse=reverse)
		else:
			x=-1
		# add skin on as an additional layer to exterior of form
		if (skin==True):
			generate_skin(t,points=exterior_points, skin_offset_factor=skin_offset_factor,offset=offset)


		if (i<bottom_layers and rs.IsCurveClosed(slice0)):
			print("bottom layer: " +str(i))
			if (skin==True):
				t.penup()
			if (interior_points):
				bottom_curve = rs.AddCurve(interior_points)
				bottom_curve = rs.CloseCurve(bottom_curve)
			else:
				bottom_curve = slice0
			point = rs.CurveAreaCentroid(slice0)[0]
			if (mode==1):
				bottom_curve = rs.OffsetCurve(bottom_curve,point,t.get_extrude_width()/2)[0]
			elif(mode==3):
				try:
					if (t.get_printer() !="lutum"):
						bottom_curve = bottom_curve
					else:
						bottom_curve = rs.OffsetCurve(bottom_curve,point,t.get_extrude_width()/2)[0]
				except:
					print("offset failed")
					bottom_curve = slice0
			t.set_speed(original_speed*.8)
			su.bottom_layer(t,bottom_curve) 
			t.set_speed(original_speed)
			t.penup()
			t.set_position_point(points[0])

		if (x==-1):
			print("error at index: " +str(i))
		else:
			layers.append(x)
		# t.pendown()

		k+=1

	t.penup()

	if (rs.IsCurveClosed(slice1)==False or rs.IsCurveClosed(slice0)==False): # if current or next curve is not closed, lift pen
		t.penup()

	return x,points


def curve_normal(curve,point):
	parameter = rs.CurveClosestPoint(curve, point)
	plane = rs.CurveFrame(curve,parameter)
	normal = plane[2]
	normal2 = plane[2]+point
	return normal,normal2

# number of calculations based on wavelength
# calculate the angles between curve0 and curve1
# find list of amplitudes based on angles and wall width
# break curve up into points
# move points in or out based on amplitude along normal vectors
def weave_points(slice0,slice1,wavelength=3.0,wall_width=4.0,mode=3,offset=False):
	points,points1,angles=find_points_and_angles(slice0,slice1,wavelength,wall_width=wall_width,mode=3)
	point_number = len(points)
	amplitudes = []
	
	for i in range (0,len(angles)):
		angle=angles[i]
		amplitude = ((wall_width)/math.cos(math.radians(angle)))
		amplitudes.append(amplitude)

	inner_points=[]
	outer_points=[]
	mid_points=[]
	weave_points=[]
	point_types=[]
	for i in range (0,len(points)):
		if (offset==True):
			o=i+2
		else:
			o=i
		normal = curve_normal(slice0,points[i])[0]

		#interior point
		if (o%4==0):
			# move in by 1/2 amplitude
			if (mode==1):
				new_point = points[i]+normal*amplitudes[i]*.5
			# move in by amplitude
			elif(mode==3):
				new_point = points[i]+normal*amplitudes[i]
			inner_points.append(new_point)
			point_types.append('i')
			weave_points.append(new_point)

		# middle point
		# not appended to weave points or point type lists
		elif(o%4==1 or o%4==3):
			# do nothing
			if (mode==1):
				new_point = points[i]
			# move in by 1/2 amplitude
			elif(mode==3):
				new_point = points[i]+normal*amplitudes[i]*.5
			mid_points.append(new_point)

		# outer point
		elif(o%4==2):
			# move out by 1/2 
			if (mode==1):
				new_point = points[i]-normal*amplitudes[i]*.5
			# do nothing
			elif(mode==3):
				new_point = points[i]
			outer_points.append(new_point)
			point_types.append('o')
			weave_points.append(new_point)

	# close the curve if the curve is closed
	if (rs.IsCurveClosed(slice0)):
		weave_points.append(weave_points[0])
		point_types.append(point_types[0])
		if (point_types[0]=='o'):
			outer_points.append(weave_points[0])
		elif (point_types[0]=='i'):
			inner_points.append(weave_points[0])
		else:
			print("point type error")

	return weave_points,point_types,inner_points,outer_points,mid_points

def follow_weave_points_turtle(t,weave_points,point_types,inner_points,outer_points,pattern_row=False):
	extruder=t.get_extruder()

	if (pattern_row is not False):
		# if the first pixel is not printing, lift up to avoid dragging to first print spot
		if ((pattern_row[0]<=.5 and extruder==0) or (pattern_row[0]>.5 and extruder==1)):
			t.penup()
			t.lift(5)
	else:
		t.pendown()

	for i in range(len(weave_points)):
		if (pattern_row is not False):
			ratio = len(pattern_row)/len(weave_points)
			pattern_index = int(round(i*ratio,1))
			if ((pattern_row[pattern_index]>.5 and extruder==0) or (pattern_row[pattern_index]<=.5 and extruder==1)):
				# if current point is inner, moving from inner to outer 
				if (point_types[i]=='i' or i==0): 
					if (t.get_pen() is False): # beginning of pattern
						t.set_position(weave_points[i].X,weave_points[i].Y) # move to position in XY only
						t.set_position_point(weave_points[i]) # move to position with penup
				# if current point is outer, moving from outer to inner
				# go back to last (inner point)
				elif(point_types[i]=='o'): 
					if (t.get_pen() is False): # beginning of pattern
						t.set_position(weave_points[i-1].X, weave_points[i-1].Y) 
						t.set_position_point(weave_points[i-1])
				t.pendown()
				t.set_position_point(weave_points[i])
			else:
				# if current point is outer, moving from inner to outer 
				# transitions insured to happen on inner points
				if (point_types[i]=='o' and t.get_pen() is True): # beginning of skip
						t.penup()
						t.lift(5) # get out of way
				elif(t.get_pen() is True): # before skip begins, move from inner to outer
					t.set_position_point(weave_points[i])

		else:
			# if there is no pattern, pen is always down
			t.pendown()
			t.set_position_point(weave_points[i])

	# if you are ending a pattern block on the outside, move to inside
	if (pattern_row is not False and point_types[len(point_types)-1]=='o'):
		if ((pattern_row[pattern_index]>.5 and extruder==0) or (pattern_row[pattern_index]<=.5 and extruder==1)):
			t.set_position_point(inner_points[0])
	elif (pattern_row is False or ps.is_pattern_empty(pattern_row,extruder=1)):
		t.set_position_point(inner_points[0])


